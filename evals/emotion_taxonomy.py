# -*- coding: utf-8 -*-
"""情绪分类学 —— 标注与评测的唯一真源（步骤 1）。

为什么要在这里再声明一份 MOODS，而不是直接 import pai.affect：
  ① 标注与评测必须能在没有后端环境的地方跑（换机、给标注员、离线）；
  ② 更重要的是——本文件与 affect.MOODS 的一致性由 tests/test_emotion_eval.py 断言强制。
      Mirrai 那次「兜底表少一个 warm，导致该态在降级路径上永远进不去」的根因，
     就是同一套状态在两个地方各写一份、没人对齐。这里刻意复制，并用测试把它钉住。

标签语义（这八条不是并列的，务必按此判）：
  平静 = 兜底类。判不出、信号弱、多类同分且都不明显时用它。
         「不确定就标平静」，不要硬猜一个情绪 —— 硬猜会把噪声喂给后续模型。
  丧痛 = 亲友离世/丧事语境。歧义极小的强信号（"去世"）单独成立；
         弱信号（"走了"）必须有亲属称谓同现才算，否则按字面理解。
  低落 / 疲惫 / 焦虑 / 愤怒 / 孤独 / 轻快 = 见各自判据。
"""
from __future__ import annotations

# ── 与 pai/affect.py:89 的 MOODS 必须逐字同序 ─────────────────────────
MOODS = ("丧痛", "焦虑", "愤怒", "孤独", "疲惫", "低落", "轻快", "平静")

FALLBACK_MOOD = "平静"

TAXONOMY_VERSION = "emotion-taxonomy-v1"

# 标注判据：labeler（人或教师模型）必须看到这一段，否则不同批次标注口径会漂。
DEFINITIONS = {
    "丧痛": "失去至亲/挚爱，或明确的丧事语境。强信号：去世、离世、过世、病逝、葬礼、头七、临终。"
            "弱信号（走了、没了、不在了）必须同现亲属称谓才算，否则按字面理解。",
    "焦虑": "对尚未发生之事的担忧、紧张、怕出错、怕被裁、坐立不安。核心是「未来」与「失控感」。",
    "愤怒": "对人对事的不满、被冒犯、想追责。含明显的攻击性或「凭什么」。",
    "孤独": "没人陪、没人懂、被孤立、想找人说话。核心是「关系缺失」。",
    "疲惫": "身体或精神电量耗尽、想睡、扛不住、上班上累了。核心是「能量低」，不是心情差。",
    "低落": "情绪往下沉、提不起劲、失望、不开心，但不到丧痛的程度。核心是「心情低」。",
    "轻快": "高兴、兴奋、想玩、好笑、有好消息。明显的正向高能量。",
    "平静": "默认值。中性陈述、信息性提问、看不出生气还是高兴、信号互相抵消 —— 都标这个。",
}

# 边界规则：最容易混的几对，给出可执行的判据。
BOUNDARIES = (
    ("低落", "丧痛", "有具体丧事/离世事实才升丧痛；只是心情沉、没提失去 → 低落"),
    ("疲惫", "低落", "只说累/睡不够/电量低 → 疲惫；带「没意思/提不起劲/失望」→ 低落"),
    ("焦虑", "低落", "指向未来且伴紧张 → 焦虑；指向已发生且伴下沉 → 低落"),
    ("孤独", "低落", "明确指向「没人陪/没人懂/一个人」→ 孤独；否则 → 低落"),
    ("轻快", "平静", "有明确正向能量词才算轻快；只是没负面情绪 → 平静"),
    ("愤怒", "低落", "有明确指向对象的攻击性、想追责、「凭什么」→ 愤怒；只是往下沉、没有对象 → 低落"),
    ("愤怒", "焦虑", "不满已发生的事、想向外追责 → 愤怒；担忧未发生的事、向内紧张 → 焦虑"),
    ("平静", "其他", "任何两类同分且都不明显 → 平静，不要靠顺序硬选"),
)

LABEL_GUIDE = "\n".join([
    "标注规则：",
    "1. 每条输入只标一个标签，取自：%s" % "、".join(MOODS),
    "2. 判不准就标「%s」。宁可漏判，不可硬猜。" % FALLBACK_MOOD,
    "3. 只看这句话本身，不要用上下文补全情绪。",
    "4. 反讽/转述他人情绪（「他说我很生气」）按说话人本人的情绪判；判不准就标平静。",
    "5. 边界对照：",
    "   " + "\n   ".join("%s vs %s：%s" % b for b in BOUNDARIES),
    "6. 定义全文：",
    "   " + "\n   ".join("%s：%s" % (k, v) for k, v in DEFINITIONS.items()),
])


def is_valid(label) -> bool:
    return label in MOODS


def validate_labels(labels):
    """返回 (合法数, 非法值集合)。教师模型输出越界是常态，必须显式挡掉。"""
    bad = sorted({str(x) for x in (labels or []) if x not in MOODS})
    return len(labels or []) - len(bad), bad


def taxonomy_block() -> str:
    """给教师模型用的提示片段。唯一住址在这里，别在别处再抄一份。"""
    return ("可选标签（有且仅有这些）：%s\n" % "、".join(MOODS)) + LABEL_GUIDE
